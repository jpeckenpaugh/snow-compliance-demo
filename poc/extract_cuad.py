#!/usr/bin/env python3
"""Extract the first N CUAD documents and normalize them for the POC.

CUAD v1 (https://github.com/The-Atticus-Project/cuad) is distributed under
CC BY 4.0. Actual shape (aok_v1.0):

    {"version": "aok_v1.0",
     "data": [ {"title": str,
                "paragraphs": [ {"context": <full contract text>,
                                 "qas": [ {"id": "<title>__<Category>",
                                           "question": str,
                                           "answers": [{"text": str, "answer_start": int}],
                                           "is_impossible": bool} ] } ] } ]}

This script downloads data.zip if needed, takes the first N docs, and writes a
compact normalized JSON (short clause snippets, no full contract text) that the
rest of the POC consumes. Run:

    python3 poc/extract_cuad.py --limit 30
"""
import argparse
import json
import pathlib
import re
import statistics
import sys
import urllib.request
import zipfile

DATA_URL = "https://github.com/The-Atticus-Project/cuad/raw/main/data.zip"
SNIPPET_CHARS = 300
DOC_ID_RE = re.compile(r"[^A-Za-z0-9]+")


def download(dest: pathlib.Path) -> pathlib.Path:
    if dest.exists():
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"downloading CUAD data.zip -> {dest}", file=sys.stderr)
    urllib.request.urlretrieve(DATA_URL, dest)
    return dest


def ensure_json(zip_path: pathlib.Path, work: pathlib.Path) -> pathlib.Path:
    target = work / "CUADv1.json"
    if target.exists():
        return target
    with zipfile.ZipFile(zip_path) as z:
        with z.open("CUADv1.json") as src, target.open("wb") as out:
            out.write(src.read())
    return target


def contract_type_from_title(title: str) -> str:
    """CUAD has no explicit contract_type field; infer it from the document title."""
    tail = title.split("-")[-1].strip()
    tail = re.sub(r"\s+\(.*?\)\s*$", "", tail)
    return tail.upper()[:80] or "UNKNOWN"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=30)
    ap.add_argument("--work", type=pathlib.Path, default=pathlib.Path("poc/.cuad_work"))
    ap.add_argument("--out", type=pathlib.Path, default=pathlib.Path("poc/data/cuad_sample.json"))
    args = ap.parse_args()

    zip_path = download(args.work / "data.zip")
    json_path = ensure_json(zip_path, args.work)
    payload = json.loads(json_path.read_text())
    docs = payload["data"][: args.limit]

    contracts, annotations, cat_counts, ctx_lengths = [], [], {}, []
    for idx, doc in enumerate(docs):
        title = doc.get("title", f"DOC-{idx}")
        contract_id = f"CUAD-{idx:04d}"
        para = (doc.get("paragraphs") or [{}])[0]
        context = para.get("context", "")
        ctx_lengths.append(len(context))
        contracts.append({
            "contract_id": contract_id,
            "title": title,
            "contract_type": contract_type_from_title(title),
            "context_chars": len(context),
        })
        for qa in para.get("qas", []):
            category = qa["id"].split("__")[-1]
            answers = qa.get("answers") or []
            present = (not qa.get("is_impossible", True)) and bool(answers)
            snippet = ""
            if answers:
                start = answers[0].get("answer_start", 0)
                snippet = context[start:start + SNIPPET_CHARS]
            cat_counts[category] = cat_counts.get(category, 0) + (1 if present else 0)
            annotations.append({
                "contract_id": contract_id,
                "category": category,
                "present": present,
                "snippet": snippet,
                "answer_start": (answers[0].get("answer_start") if answers else None),
            })

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps({
        "source": "The Atticus Project CUAD, CUADv1.json, CC BY 4.0",
        "limit": args.limit,
        "contracts": contracts,
        "annotations": annotations,
    }, indent=1))

    # --- Shape report -------------------------------------------------------
    report = args.out.parent.parent / "analysis" / "cuad_shape_report.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# CUAD first-%d shape report" % len(contracts),
        "",
        "_Generated by `poc/extract_cuad.py` from CUADv1.json (CC BY 4.0)._",
        "",
        "## Structural facts",
        f"- Documents extracted: **{len(contracts)}** of 510",
        f"- Clause categories per document: **{len(cat_counts)}** (CUAD-wide: 41)",
        f"- Total annotations: **{len(annotations)}**",
        f"- Context length (chars): min {min(ctx_lengths)}, median {int(statistics.median(ctx_lengths))}, max {max(ctx_lengths)}",
        "",
        "## Contract types inferred from titles (no explicit type field exists)",
        "",
    ]
    by_type = {}
    for c in contracts:
        by_type[c["contract_type"]] = by_type.get(c["contract_type"], 0) + 1
    for t, n in sorted(by_type.items(), key=lambda kv: -kv[1]):
        lines.append(f"- {t}: {n}")
    lines += ["", "## Clause-category presence across the sample", "",
              "| Category | Present in N docs |", "| --- | --- |"]
    for cat, n in sorted(cat_counts.items(), key=lambda kv: -kv[1]):
        lines.append(f"| {cat} | {n} |")
    lines.append("")
    report.write_text("\n".join(lines))
    print(f"wrote {args.out} and {report}")


if __name__ == "__main__":
    main()
